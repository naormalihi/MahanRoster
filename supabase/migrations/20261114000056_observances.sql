-- Observances that are not rest days (מועדים שאינם שבתון) on the holiday calendar.
--
-- * A day type "מועד (לא שבתון)" – not a holiday for weekend balancing.
-- * Holidays by name grow by: hanukkah (ערב חנוכה = the first candle, then its 8 days),
--   purim (ערב פורים, פורים, שושן פורים), fast (צום גדליה, עשרה בטבת, תענית אסתר, י"ז בתמוז,
--   ערב תשעה באב and תשעה באב) and minor (ט"ו בשבט, ל"ג בעומר, יום ירושלים, ט"ו באב).
-- * A multiplier with no holiday chosen still means the rest-day holidays only, so the ones
--   already defined give the same points; an observance counts only when chosen by name.
-- * The days for 2026–2035 are added where the calendar has nothing on that day.
-- =============================================================================

